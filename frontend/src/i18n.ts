export type TranslationKey = keyof typeof translations.fr;
export function getLanguage(): GrindlyLanguage {
    const value = localStorage.getItem("grindly-language") || "fr";
    return LANGUAGES.some(item => item.value === value) ? value as GrindlyLanguage : "fr";
}
export function t(language: string, key: TranslationKey): string {
    const dictionary = translations[language as GrindlyLanguage] || translations.fr;
    return (dictionary as Record<string, string>)[key] || translations.fr[key] || key;
}
export function applyLanguage(language: GrindlyLanguage) {
    localStorage.setItem("grindly-language", language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
    window.dispatchEvent(new CustomEvent("grindly-language-change", { detail: { language } }));
}
